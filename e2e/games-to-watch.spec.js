import { expect, test } from '@playwright/test'

test('a Games to Watch link opens without rendering results', async ({ page }) => {
  await page.addInitScript(() => {
    const check = () => {
      if (document.querySelector('.overview-table')) window.overviewRendered = true
    }
    new MutationObserver(check).observe(document, { childList: true, subtree: true })
  })
  await page.goto('/?tab=watch&scenario=stale-data&pool=week-02')
  const table = page.getByRole('table', { name: 'Games to Watch rankings' })
  await expect(table).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Game overview' })).toHaveCount(0)
  expect(await page.evaluate(() => Boolean(window.overviewRendered))).toBe(false)
  const showPicks = page.getByRole('checkbox', { name: 'Show player picks' })
  await expect(showPicks).not.toBeChecked()
  await expect(table.getByRole('columnheader', { name: 'Alex' })).toHaveCount(0)
  await showPicks.check()
  await expect(table.getByRole('columnheader', { name: 'Alex' })).toBeVisible()
  const game = table.getByRole('row').filter({ hasText: 'DAL @ PHI' })
  await expect(game.getByRole('cell', { name: 'PHI, confidence 1', exact: true })).toHaveText('PHI1')
  await expect(game.getByRole('cell', { name: 'DAL, confidence 2', exact: true })).toHaveText('DAL2')
  await page.getByRole('button', { name: 'Full Season' }).click()
  await expect(table.getByRole('cell', { name: 'PHI, confidence 1', exact: true })).toHaveCount(2)
  await expect(table).not.toContainText(/20.?27|17.?17/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await showPicks.uncheck()
  await expect(table.getByRole('columnheader', { name: 'Alex' })).toHaveCount(0)
})

test('Games to Watch fits the viewport and keeps weekly navigation available', async ({ page }) => {
  await page.goto('/?scenario=stale-data&pool=week-02')
  await page.getByRole('button', { name: 'Games to Watch', exact: true }).click()
  const section = page.getByRole('region', { name: 'Games to Watch' })
  const table = section.getByRole('table')
  const week = page.getByLabel('Week', { exact: true })
  await expect(section.getByRole('button', { name: 'Current Week' })).toHaveAttribute('aria-pressed', 'true')
  await expect(table.getByRole('row')).toHaveCount(2)
  await week.selectOption('week-01')
  await expect(table.getByRole('row')).toHaveCount(5)
  await section.getByRole('button', { name: 'Full Season' }).click()
  await expect(week).toHaveCount(0)
  await expect(table.getByRole('row')).toHaveCount(6)
  await expect(table.getByRole('columnheader', { name: 'Week', exact: true })).toBeVisible()
  await expect(section).not.toContainText(/20.?27|17.?17/)
  const notes = section.getByRole('region', { name: 'How the rankings work' })
  await expect(notes).toBeVisible()
  await expect(notes.locator('dt')).toHaveText(['Uncertainty', 'WP Swings', 'Late-Game Suspense', 'Team Quality'])
  expect(await table.evaluate((element) => element.parentElement.nextElementSibling?.getAttribute('aria-labelledby'))).toBe('watch-scoring-title')
  await section.getByText('Scoring Settings', { exact: true }).click()
  const quality = section.getByRole('slider', { name: 'Team Quality weight' })
  await quality.press('End')
  await expect(quality).toHaveAttribute('aria-valuetext', '100%')
  await expect(section.getByRole('slider', { name: 'Uncertainty weight' })).toHaveValue('0')
  await section.getByRole('button', { name: 'Reset to default weights' }).click()
  await expect(quality).toHaveValue('10')
  await expect(section.getByRole('slider', { name: 'Uncertainty weight' })).toHaveValue('30')
  const qualityNumber = section.getByRole('spinbutton', { name: 'Team Quality weight percentage' })
  await qualityNumber.fill('40')
  await qualityNumber.press('Enter')
  await expect(quality).toHaveValue('40')
  const sum = await section.getByRole('spinbutton').evaluateAll((inputs) => inputs.reduce((total, input) => total + input.valueAsNumber, 0))
  expect(sum).toBe(100)
  await qualityNumber.fill('75')
  await qualityNumber.press('Escape')
  await expect(qualityNumber).toHaveValue('40')
  await qualityNumber.fill('110')
  await qualityNumber.press('Tab')
  await expect(qualityNumber).toHaveValue('100')
  const scopeFits = await section.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)
  expect(scopeFits).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
